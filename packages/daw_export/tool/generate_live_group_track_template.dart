import 'dart:convert';
import 'dart:io';

import 'package:xml/xml.dart';

/// Regenerates `lib/src/live_group_track_template.dart` from the reference
/// set `test/corpus/group.als`: its Group track, which `buildAls` copies
/// once per looper track. Run from the package root after replacing the
/// corpus with sets saved by a newer Live:
///
/// ```sh
/// dart run tool/generate_live_group_track_template.dart
/// ```
void main() {
  const source = 'test/corpus/group.als';
  final xml = utf8.decode(gzip.decode(File(source).readAsBytesSync()));
  final group = XmlDocument.parse(xml)
      .findAllElements('GroupTrack')
      .single
      .toXmlString();
  if (group.contains("'''")) {
    stderr.writeln('$source contains three quotes in a row');
    exit(1);
  }
  File('lib/src/live_group_track_template.dart').writeAsStringSync(
    '// Generated by tool/generate_live_group_track_template.dart from\n'
    '// $source. Do not edit by hand.\n'
    '// ignore_for_file: leading_newlines_in_multiline_strings\n'
    '// ignore_for_file: unnecessary_raw_strings\n'
    '\n'
    '/// A Group track as Live 12 writes it, with no devices: `buildAls`\n'
    '/// copies every group it writes from it.\n'
    "const String liveGroupTrackTemplate = r'''$group''';\n",
  );
}
