import 'dart:convert';
import 'dart:io';

import 'package:xml/xml.dart';

/// Regenerates the templates `buildAls` copies from, out of reference sets
/// Live saved. Run from the package root after replacing the corpus with
/// sets saved by a newer Live:
///
/// ```sh
/// dart run tool/generate_live_set_template.dart
/// ```
///
/// - `lib/src/live_set_template.dart`: `test/corpus/automation.als`, whole.
/// - `lib/src/live_device_template.dart`: from `test/corpus/segno_vst3.als`,
///   its track's first Segno plugin device and its Audio Effect Rack with
///   one chain and no devices in it.
void main() {
  const setSource = 'test/corpus/automation.als';
  final xml = _read(setSource);
  File('lib/src/live_set_template.dart').writeAsStringSync(
    '// Generated by tool/generate_live_set_template.dart from\n'
    '// $setSource. Do not edit by hand.\n'
    '// ignore_for_file: leading_newlines_in_multiline_strings\n'
    '// ignore_for_file: unnecessary_raw_strings\n'
    '\n'
    '/// A set Live 12 saved, with one audio track holding an Arrangement\n'
    '/// clip, a Session clip and volume and activator envelopes:\n'
    '/// `buildAls` copies everything it writes from it.\n'
    "const String liveSetTemplate = r'''$xml''';\n",
  );

  const deviceSource = 'test/corpus/segno_vst3.als';
  final devices = XmlDocument.parse(_read(deviceSource))
      .findAllElements('AudioTrack')
      .first
      .getElement('DeviceChain')!
      .getElement('DeviceChain')!
      .getElement('Devices')!;
  final plugin = devices.findElements('PluginDevice').first.copy();
  final rack = devices.findElements('AudioEffectGroupDevice').first.copy();
  final branches = rack.getElement('Branches')!;
  final branch = branches.childElements.first.copy();
  branches.children.clear();
  branch
      .getElement('DeviceChain')!
      .getElement('AudioToAudioDeviceChain')!
      .getElement('Devices')!
      .children
      .clear();
  branches.children.add(branch);
  File('lib/src/live_device_template.dart').writeAsStringSync(
    '// Generated by tool/generate_live_set_template.dart from\n'
    '// $deviceSource. Do not edit by hand.\n'
    '// ignore_for_file: leading_newlines_in_multiline_strings\n'
    '// ignore_for_file: unnecessary_raw_strings\n'
    '\n'
    '/// A Segno plugin device as Live 12 saved it: `buildAls` copies every\n'
    '/// plugin it writes from it.\n'
    'const String livePluginDeviceTemplate = '
    "r'''${_checked(plugin.toXmlString(), deviceSource)}''';\n"
    '\n'
    '/// An Audio Effect Rack as Live 12 saved it, with one chain and no\n'
    '/// devices: `buildAls` copies every rack, and every chain of it, from\n'
    '/// it.\n'
    'const String liveRackDeviceTemplate = '
    "r'''${_checked(rack.toXmlString(), deviceSource)}''';\n",
  );
}

String _read(String path) =>
    _checked(utf8.decode(gzip.decode(File(path).readAsBytesSync())), path);

String _checked(String xml, String source) {
  if (xml.contains("'''")) {
    stderr.writeln('$source contains three quotes in a row');
    exit(1);
  }
  return xml;
}
