import 'dart:convert';
import 'dart:io';

/// Regenerates `lib/src/live_set_template.dart` from the reference set Live
/// saved, `test/corpus/automation.als`. Run from the package root after
/// replacing the corpus with sets saved by a newer Live:
///
/// ```sh
/// dart run tool/generate_live_set_template.dart
/// ```
void main() {
  const source = 'test/corpus/automation.als';
  final xml = utf8.decode(gzip.decode(File(source).readAsBytesSync()));
  if (xml.contains("'''")) {
    stderr.writeln('$source contains three quotes in a row');
    exit(1);
  }
  File('lib/src/live_set_template.dart').writeAsStringSync(
    '// Generated by tool/generate_live_set_template.dart from\n'
    '// $source. Do not edit by hand.\n'
    '// ignore_for_file: leading_newlines_in_multiline_strings\n'
    '// ignore_for_file: unnecessary_raw_strings\n'
    '\n'
    '/// A set Live 12 saved, with one audio track holding an Arrangement\n'
    '/// clip, a Session clip and volume and activator envelopes:\n'
    '/// `buildAls` copies everything it writes from it.\n'
    "const String liveSetTemplate = r'''$xml''';\n",
  );
}
